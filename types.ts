export type PaymentType = 'Installment' | 'Delayed';
export type PaymentMethod = 'Cash' | 'BANK' | 'E-Wallet';
export type InterestType = 'percentage' | 'fixed';

export interface PurchaseItem {
  id: string;
  name: string;
  amount: number;
  extraBalance?: number; // Additional balance, surcharge, or extra adjustment on this order
  date: string; // Order / declared date
  dueDate?: string; // Maturity / due date specifically for this order item
  note?: string;
  attachment?: Attachment;
  // Single order interest policy
  dailyInterestRate?: number; // Custom daily interest rate (e.g., RM5/d or 0.2%/d)
  interestType?: InterestType; // 'fixed' | 'percentage'
  calculatedInterest?: number; // Accrued interest for this item
  overdueDays?: number; // Days past the specific order due date
}

export interface PaymentRecord {
  id: string;
  amount: number;
  method: PaymentMethod;
  date: string;
  note?: string;
  attachment?: Attachment;
}

export interface SystemNote {
  id: string;
  timestamp: string;
  content: string;
  isPinned?: boolean;
}

export interface Attachment {
  id: string;
  name: string;
  data: string; // Base64 or URL
  type: 'image' | 'document';
  description?: string;
  fileSize?: number;
}

export interface LedgerRecord {
  id: string; 
  shareKey: string; // Secure share token
  accessOtp?: string; // 6-digit One-Time Passcode generated by administrator
  userName: string;
  type: PaymentType;
  totalAmount: number;
  paidAmount: number;
  paymentCycle?: 'Day' | 'Weekly' | 'Monthly';
  cycleCount?: number;
  startDate: string;
  endDate?: string;
  nextPaymentDate?: string;
  // Overdue interest policy (Overdue Days x Daily Rate)
  interestEnabled?: boolean; // Toggle for interest calculation
  dailyInterestRate?: number; // Daily rate (e.g. RM10 or 0.5%)
  interestType?: InterestType; // 'fixed' or 'percentage'
  calculatedInterest?: number; // Real-time accrued overdue interest
  overdueDays?: number; // Number of days overdue
  waiveInterest?: boolean; // Waive interest flag
  items: PurchaseItem[];
  payments: PaymentRecord[];
  notes: SystemNote[];
  attachments: Attachment[];
  status: 'Active' | 'Settled' | 'Overdue';
}

export interface MonthlyTrend {
  month: string;
  amount: number;
}

export interface DashboardStats {
  totalValuation: number;
  totalOutstanding: number;
  activeCustomers: number;
  collectedThisMonth: number;
  collectionRate: number;
  overdueAmount: number;
  totalInterestAmount: number; // Total accrued interest across all protocols
  monthlyTrend: MonthlyTrend[];
}

export interface AppSettings {
  brandName: string;
  logoUrl: string | null;
  signatureUrl: string | null;
  signerName?: string;
  signerTitle?: string;
}
